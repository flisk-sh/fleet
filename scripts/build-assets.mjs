// Builds src/assets.js: the icons and the social preview image, embedded as base64 so the Worker serves them with no asset
// hosting. Needs rsvg-convert (librsvg) and Google Chrome; run it only when assets/ changes.
//   bun scripts/build-assets.mjs
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const tmp = mkdtempSync(join(tmpdir(), 'fleet-assets-'));
const run = (cmd, args) => {
  const p = Bun.spawnSync([cmd, ...args]);
  if (p.exitCode !== 0) throw new Error(`${cmd} failed: ${p.stderr.toString().slice(0, 300)}`);
};
const b64 = (path) => readFileSync(path).toString('base64');

// 32 px PNG for favicon.ico (an ICO may hold a PNG), 180 px square for the iPhone home-screen icon, 512 px for manifests.
run('rsvg-convert', ['-w', '32', '-h', '32', `${root}assets/icon.svg`, '-o', join(tmp, 'f32.png')]);
run('rsvg-convert', ['-w', '48', '-h', '48', `${root}assets/icon.svg`, '-o', join(tmp, 'f48.png')]);
run('rsvg-convert', ['-w', '180', '-h', '180', `${root}assets/icon-square.svg`, '-o', join(tmp, 'apple.png')]);
run('rsvg-convert', ['-w', '512', '-h', '512', `${root}assets/icon.svg`, '-o', join(tmp, 'icon512.png')]);
const ico = (images) => {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size, e);
    head.writeUInt8(size, e + 1);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...images.map((i) => i.data)]);
};
writeFileSync(join(tmp, 'favicon.ico'), ico([{ size: 32, data: readFileSync(join(tmp, 'f32.png')) }, { size: 48, data: readFileSync(join(tmp, 'f48.png')) }]));

// Social preview: 1200 x 630, drawn as HTML so it uses the site's fonts, then screenshotted by headless Chrome.
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
run(chrome, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1', '--window-size=1200,630', '--virtual-time-budget=8000', `--screenshot=${join(tmp, 'og.png')}`, `file://${root}assets/og.html`]);

const files = { 'icon.svg': readFileSync(`${root}assets/icon.svg`).toString('base64'), 'favicon.ico': b64(join(tmp, 'favicon.ico')), 'apple-touch-icon.png': b64(join(tmp, 'apple.png')), 'icon-512.png': b64(join(tmp, 'icon512.png')), 'og.png': b64(join(tmp, 'og.png')) };
writeFileSync(`${root}src/assets.js`, `// GENERATED by scripts/build-assets.mjs from assets/. Do not edit by hand.\nexport const ASSETS = ${JSON.stringify(files, null, 1)};\n`);
console.log(Object.entries(files).map(([k, v]) => `${k} ${Math.round((v.length * 3) / 4 / 1024)} KB`).join('\n'));
